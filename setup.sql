-- 3. Function: count books

CREATE OR REPLACE FUNCTION count_books
RETURN NUMBER
IS
    total_books NUMBER;
BEGIN
    SELECT COUNT(*) INTO total_books FROM books;
    RETURN total_books;
END;
/

-- 4. Function: get book price

CREATE OR REPLACE FUNCTION get_book_price(
    p_book_id NUMBER
)
RETURN NUMBER
IS
    book_price NUMBER;
BEGIN
    SELECT price INTO book_price
    FROM books
    WHERE book_id = p_book_id;

    RETURN book_price;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN NULL;
END;
/

-- 5. Procedure: place an order

CREATE OR REPLACE PROCEDURE place_order(
    p_customer_id IN NUMBER,
    p_book_id IN NUMBER,
    p_quantity IN NUMBER
)
IS
    book_price NUMBER;
    available_stock NUMBER;
BEGIN
    IF p_quantity <= 0 THEN
        RAISE_APPLICATION_ERROR(-20001,
            'Quantity must be greater than zero');
    END IF;

    SELECT price, stock
    INTO book_price, available_stock
    FROM books
    WHERE book_id = p_book_id
    FOR UPDATE;

    IF available_stock < p_quantity THEN
        RAISE_APPLICATION_ERROR(-20002,
            'Not enough stock');
    END IF;

    INSERT INTO orders (
        customer_id, book_id, quantity, total
    )
    VALUES (
        p_customer_id,
        p_book_id,
        p_quantity,
        book_price * p_quantity
    );

    UPDATE books
    SET stock = stock - p_quantity
    WHERE book_id = p_book_id;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20003,
            'Book not found');
END;
/